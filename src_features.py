import pandas as pd


FEATURE_COLUMNS = [
    "RecencyDays",
    "CustomerTenureDays",
    "TotalOrders",
    "TotalQuantity",
    "AverageOrderValue",
    "PurchaseFrequency",
    "AverageRevenuePerOrder",
    "HistoricalRevenue",
]


def build_customer_features(
    transactions: pd.DataFrame,
    cutoff_date,
) -> pd.DataFrame:
    """Calculate customer features using history before a cutoff."""

    cutoff = pd.Timestamp(cutoff_date)
    history = transactions[
        transactions["InvoiceDate"] < cutoff
    ].copy()

    if history.empty:
        raise ValueError("No historical transactions before cutoff.")

    history["InvoiceNo"] = history["InvoiceNo"].astype(str)

    grouped = history.groupby("CustomerID")

    customers = grouped.agg(
        FirstPurchase=("InvoiceDate", "min"),
        LastPurchase=("InvoiceDate", "max"),
        HistoricalRevenue=("Revenue", "sum"),
        TotalOrders=("InvoiceNo", "nunique"),
        TotalQuantity=("Quantity", "sum"),
        AverageOrderValue=("Revenue", "mean"),
    )

    customers["RecencyDays"] = (
        cutoff - customers["LastPurchase"]
    ).dt.total_seconds() / 86400

    customers["CustomerTenureDays"] = (
        customers["LastPurchase"] - customers["FirstPurchase"]
    ).dt.total_seconds().div(86400).clip(lower=0)

    customers["PurchaseFrequency"] = (
        customers["TotalOrders"]
        / (customers["CustomerTenureDays"] / 30 + 1)
    )

    customers["AverageRevenuePerOrder"] = (
        customers["HistoricalRevenue"]
        / customers["TotalOrders"].clip(lower=1)
    )

    customers = customers.replace(
        [float("inf"), float("-inf")], 0
    ).fillna(0)

    return customers[FEATURE_COLUMNS].copy()


def build_future_revenue_target(
    transactions: pd.DataFrame,
    cutoff_date,
    horizon_days: int = 90,
) -> pd.Series:
    """Calculate revenue in the period after the feature cutoff."""

    cutoff = pd.Timestamp(cutoff_date)
    horizon_end = cutoff + pd.Timedelta(days=horizon_days)

    future = transactions[
        (transactions["InvoiceDate"] >= cutoff)
        & (transactions["InvoiceDate"] < horizon_end)
    ]

    target = future.groupby("CustomerID")["Revenue"].sum()
    target.name = "FutureRevenue"

    return target