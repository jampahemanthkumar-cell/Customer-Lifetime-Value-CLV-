import numpy as np
import pandas as pd

from sklearn.ensemble import (
    HistGradientBoostingRegressor,
    RandomForestRegressor,
)
from sklearn.impute import SimpleImputer
from sklearn.linear_model import Ridge
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score,
)
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from xgboost import XGBRegressor


def get_models():
    """Return a collection of regression pipelines."""

    return {
        "Ridge": make_pipeline(
            SimpleImputer(strategy="median"),
            StandardScaler(),
            Ridge(alpha=10.0),
        ),
        "Random Forest": make_pipeline(
            SimpleImputer(strategy="median"),
            RandomForestRegressor(
                n_estimators=250,
                max_depth=12,
                min_samples_leaf=3,
                random_state=42,
                n_jobs=-1,
            ),
        ),
        "Hist Gradient Boosting": make_pipeline(
            SimpleImputer(strategy="median"),
            HistGradientBoostingRegressor(
                max_iter=200,
                learning_rate=0.06,
                l2_regularization=1.0,
                random_state=42,
            ),
        ),
        "XGBoost": make_pipeline(
            SimpleImputer(strategy="median"),
            XGBRegressor(
                n_estimators=300,
                max_depth=5,
                learning_rate=0.04,
                subsample=0.85,
                colsample_bytree=0.85,
                objective="reg:squarederror",
                random_state=42,
                n_jobs=-1,
            ),
        ),
    }


def evaluate_model(model, X_test, y_test):
    """Evaluate non-negative revenue predictions."""

    predictions = np.maximum(model.predict(X_test), 0)

    return {
        "MAE": float(mean_absolute_error(y_test, predictions)),
        "RMSE": float(
            np.sqrt(mean_squared_error(y_test, predictions))
        ),
        "R2": float(r2_score(y_test, predictions)),
    }


def fit_and_compare(X_train, y_train, X_test, y_test):
    """Fit models and select the one with lowest validation MAE."""

    results = []
    fitted_models = {}

    for name, model in get_models().items():
        model.fit(X_train, y_train)

        metrics = evaluate_model(model, X_test, y_test)
        results.append({"Model": name, **metrics})
        fitted_models[name] = model

    results_df = (
        pd.DataFrame(results)
        .sort_values("MAE")
        .reset_index(drop=True)
    )

    best_name = results_df.iloc[0]["Model"]

    return fitted_models[best_name], best_name, results_df