import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler


def segment_customers(
    customer_features: pd.DataFrame,
    n_clusters: int = 4,
) -> pd.DataFrame:
    """Segment customers using recency, frequency and monetary value."""

    if not 2 <= n_clusters <= 10:
        raise ValueError("n_clusters must be between 2 and 10.")

    required = [
        "RecencyDays",
        "TotalOrders",
        "HistoricalRevenue",
    ]

    missing = [
        column for column in required
        if column not in customer_features.columns
    ]

    if missing:
        raise ValueError(f"Missing segmentation columns: {missing}")

    result = customer_features.copy()

    rfm = pd.DataFrame(index=result.index)
    rfm["Recency"] = result["RecencyDays"].clip(lower=0)
    rfm["Frequency"] = np.log1p(
        result["TotalOrders"].clip(lower=0)
    )
    rfm["Monetary"] = np.log1p(
        result["HistoricalRevenue"].clip(lower=0)
    )

    if len(rfm) < n_clusters:
        raise ValueError(
            "There are fewer customers than requested clusters."
        )

    scaler = StandardScaler()
    scaled = scaler.fit_transform(rfm)

    model = KMeans(
        n_clusters=n_clusters,
        random_state=42,
        n_init=10,
    )

    result["Segment"] = model.fit_predict(scaled)

    return result


def summarize_segments(segmented: pd.DataFrame) -> pd.DataFrame:
    """Summarize the average purchasing behavior of each segment."""

    return segmented.groupby("Segment").agg(
        CustomerCount=("Segment", "size"),
        AverageRecency=("RecencyDays", "mean"),
        AverageOrders=("TotalOrders", "mean"),
        AverageRevenue=("HistoricalRevenue", "mean"),
    ).reset_index()