import pandas as pd


COLUMN_ALIASES = {
    "CustomerID": ["CustomerID", "Customer ID", "customer_id"],
    "InvoiceDate": ["InvoiceDate", "Invoice Date", "invoice_date"],
    "Quantity": ["Quantity", "quantity"],
    "UnitPrice": ["UnitPrice", "Unit Price", "unit_price"],
    "InvoiceNo": ["InvoiceNo", "Invoice", "invoice_no"],
}


def load_transactions(path: str) -> pd.DataFrame:
    """Load and validate customer transaction records."""
    df = pd.read_csv(path, encoding="utf-8-sig")

    rename = {}
    for standard, candidates in COLUMN_ALIASES.items():
        match = next(
            (column for column in candidates if column in df.columns),
            None,
        )
        if match:
            rename[match] = standard

    df = df.rename(columns=rename)

    required = [
        "CustomerID",
        "InvoiceDate",
        "Quantity",
        "UnitPrice",
    ]
    missing = [column for column in required if column not in df.columns]

    if missing:
        raise ValueError(
            f"Missing columns: {missing}. "
            f"Found columns: {list(df.columns)}"
        )

    df["CustomerID"] = (
        df["CustomerID"].astype("string").str.strip()
    )
    df["InvoiceDate"] = pd.to_datetime(
        df["InvoiceDate"], errors="coerce", dayfirst=True
    )
    df["Quantity"] = pd.to_numeric(
        df["Quantity"], errors="coerce"
    )
    df["UnitPrice"] = pd.to_numeric(
        df["UnitPrice"], errors="coerce"
    )

    df = df.dropna(subset=required)

    df = df[
        (df["CustomerID"] != "")
        & (df["Quantity"] > 0)
        & (df["UnitPrice"] > 0)
    ].copy()

    df["Revenue"] = df["Quantity"] * df["UnitPrice"]

    if "InvoiceNo" not in df.columns:
        raise ValueError(
            "InvoiceNo is required to calculate distinct orders. "
            "Map your dataset's invoice column before continuing."
        )

    df["InvoiceNo"] = df["InvoiceNo"].astype(str)

    if df.empty:
        raise ValueError("No valid sales records remain after cleaning.")

    return df.reset_index(drop=True)